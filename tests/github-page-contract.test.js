const fs=require('fs');
const assert=(c,m)=>{if(!c)throw new Error(m)};
const setup=fs.readFileSync('github-setup.html','utf8');
const backend=fs.readFileSync('local-github-backend.js','utf8');
const integration=fs.readFileSync('assets/github-integration.js','utf8');
const index=fs.readFileSync('index.html','utf8');
const installer=fs.readFileSync('INSTALL_ON_MY_COMPUTER.bat','utf8');
const launcher=fs.readFileSync('desktop-launcher.js','utf8');
assert(setup.includes('<h1 id="page-title">GitHub</h1>') && setup.includes('Connect GitHub'),'GitHub page must exist and explain account connection');
assert(setup.includes('Choose a repository'),'GitHub page must let the learner choose a repository');
assert(setup.includes('Add &amp; use repository'),'GitHub page must let the learner add a repository');
assert(setup.includes('csai-github-preferred-repo'),'GitHub page must persist the selected repository for publishing tools');
assert(index.includes('href="github-setup.html"'),'home page must link to GitHub');
