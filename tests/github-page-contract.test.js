assert(!backend.includes('DEFAULT_REPOSITORY'),'backend must not contain a default repository constant');
assert(!integration.includes('DEFAULT_REPO'),'integration must not contain a default repository constant');
assert(!launcher.includes('TARGET_REPO'),'launcher must not contain a fixed repository target');
assert(!installer.includes('gh repo view '),'installer must not probe any fixed repository');
