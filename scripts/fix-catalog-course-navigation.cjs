const fs=require('fs');
const path=require('path');
const root=process.cwd();
const file=path.join(root,'assets','catalog-recovery.js');
const injector=path.join(root,'scripts','inject-course-loader.cjs');
if(!fs.existsSync(file))throw new Error('catalog-recovery.js missing');
if(!fs.existsSync(injector))throw new Error('inject-course-loader.cjs missing');
let src=fs.readFileSync(file,'utf8');
const old="var id=b.getAttribute('data-scr-course');remove();if(typeof window.cxOpen==='function')window.cxOpen(id)";
const replacement="var id=b.getAttribute('data-scr-course');var safe=String(id||'').replace(/[^A-Za-z0-9._-]/g,'');if(!safe)return;var url='/courses/'+encodeURIComponent(safe)+'.html';x.preventDefault();x.stopPropagation();location.assign(url);return";
if(src.includes(old))src=src.replace(old,replacement);
if(src.includes(old))throw new Error('Catalog still removes itself before course navigation');
if(!src.includes("location.assign(url);return"))throw new Error('Direct static catalog navigation patch missing');
fs.writeFileSync(file,src,'utf8');
let loader=fs.readFileSync(injector,'utf8');
if(!/const catalogPath = '\/assets\/catalog-recovery\.js\?v=[^']+';/.test(loader))throw new Error('Catalog cache version declaration missing');
loader=loader.replace(/const catalogPath = '\/assets\/catalog-recovery\.js\?v=[^']+';/,"const catalogPath = '/assets/catalog-recovery.js?v=20260808-5';");
fs.writeFileSync(injector,loader,'utf8');
console.log('Catalog course navigation now stays covered until static navigation and uses cache version 20260808-5.');
